using Common;

namespace ArealMapLib;

/// <summary>
/// Ареал: многоугольник на карте (в 30% случаев не выпуклый) с точкой, площадью, нормалью и соседями по рёбрам. Запись в файле: 0x38 байт заголовка,
/// затем <c>V</c> вершин по 12 байт и <c>V</c> рёбер по 8 байт. Игра строит из них граф проходимости (<c>ArealMap.dll</c>).
/// Поля заголовка +0x0C, +0x24 и +0x2C всегда равны 0 (30951 ареал в 29 картах) и в модели не хранятся.
/// </summary>
/// <param name="Center">[+0x00] Центральная точка ареала (x, y, z).</param>
/// <param name="Area">[+0x10] Площадь многоугольника в плоскости XY (совпадает с формулой Гаусса по вершинам с точностью до округления); у однотипных треугольников сетки одинакова (например 1945.5).</param>
/// <param name="Normal">[+0x14] Нормаль плоскости ареала (единичный вектор; средний nz по значениям [+0x28] 0.84..0.99).</param>
/// <param name="Flag0x20">[+0x20] Признак 0 или 1 (1 у 5396 из 30951 ареалов); смысл не выяснен.</param>
/// <param name="Mask0x28">[+0x28] Целое, похожее на битовую маску свойств: значения 1..29, 240, 242 (21 значение по всем картам;
/// в карте 11 - 1, 2, 3, 240; ареалы со значением 3 содержат все внешние границы карты); смысл не выяснен.</param>
/// <param name="Vertices">Вершины многоугольника по порядку обхода (против часовой стрелки у всех выпуклых; 3 вершины у половины ареалов).</param>
/// <param name="Edges">Рёбра: <c>Edges[i]</c> - отрезок от <c>Vertices[i]</c> до <c>Vertices[(i + 1) % V]</c>.</param>
public sealed record ArealRecord(
    Vector3 Center,
    float Area,
    Vector3 Normal,
    int Flag0x20,
    int Mask0x28,
    Vector3[] Vertices,
    ArealEdge[] Edges);
