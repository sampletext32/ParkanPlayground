namespace ControlLib;

/// <summary>
/// Тип записи агента: 4CC типа ресурса в архивах NRes <c>objects.rlb</c> и <c>fortif.rlb</c>. Значения совпадают с <c>AgentType</c> в <c>CAgent::try_load</c> (AniMesh.dll).
/// Агент - запись без заголовка: массив 64-байтных ссылок, число ссылок = размер / 64. Статистика: BTLU - 55, INTO - 192, EXTO - 127, BULL - 53, STAT - 66, FORT - 30, WPNS - 5, SUNO - 2.
/// </summary>
public enum AgentRecordType : uint
{
    /// <summary>Юнит (робот, животное, здание-ангар): 7 ссылок (448 байт), у зданий <c>fortif.rlb</c> 5 ссылок (320 байт). 55 записей.</summary>
    Btlu = 0x554C5442,   // "BTLU"

    /// <summary>Снаряд: 5 ссылок (320 байт). 53 записи; имя берётся из <c>Resource</c> предмета CTL типа 0x02/0x1E.</summary>
    Bull = 0x4C4C5542,   // "BULL"

    /// <summary>Оружие (корневое): 5 ссылок (320 байт). 5 записей, источник ссылки на них не найден.</summary>
    Wpns = 0x534E5057,   // "WPNS"

    /// <summary>Статический объект (камни, деревья): 6 ссылок (384 байта), шестая всегда пустая. 66 записей; имена прописаны в <c>data.tma</c> миссий.</summary>
    Stat = 0x54415453,   // "STAT"

    /// <summary>Внутренний элемент (двигатель, радар, щит, батарея, ремонт, броня, патроны): 5 ссылок (320 байт), грузится как приставка к родителю. 192 записи.</summary>
    Into = 0x4F544E49,   // "INTO"

    /// <summary>Внешний элемент (башня, орудие, деталь): 5 ссылок (320 байт). 127 записей.</summary>
    Exto = 0x4F545845,   // "EXTO"

    /// <summary>Укрепление (здание): ссылка на BTLU-здание и на BASE (<c>.bas</c>), 2 ссылки (128 байт). 30 записей.</summary>
    Fort = 0x54524F46,   // "FORT"

    /// <summary>Солнце: ссылка на <c>.sun</c> (<c>system.rlb</c>) и на образ (FXID <c>effects.rlb</c>), 2 ссылки (128 байт). 2 записи.</summary>
    Suno = 0x4F4E5553,   // "SUNO"
}
