namespace ControlLib;

/// <summary>
/// Условие выполнения команды (12 байт): проверка булевых признаков состояния объекта (<c>ControlCommandConditionState</c>,
/// <c>EvaluateControlCommandCondition</c> Control.dll 0x10002360). Признаки - 14 флагов состояния (биты 0..13), критическое разрушение (бит 0x4000)
/// и режим состояния 2 (бит 0x8000).
/// </summary>
/// <remarks>
/// Логика: если в <see cref="ConditionFlags"/> нет 0x40000000 и 0x20000000, команда выполняется всегда. Режим 0x40000000 («или»): команда выполняется,
/// если хотя бы один выбранный маской бит совпал с ожидаемым значением (признак установлен, а при бите в <see cref="ConditionInvertMask"/> - сброшен).
/// Режим 0x20000000 («и»): должны совпасть все выбранные биты. Остальные биты флагов (0x80000000, 0x10000000) движок не читает.
/// Статистика по 1271 команде: без условия - 1204; 0x40000000 - 41; 0xC0000000 - 20; 0xD0000000 - 6. Маски: 0x8000 - 40, 0x800 - 16, 0x4 - 13, 0x4000 - 8,
/// 0x1, 0x1000, 0x200 - по 4. Инверсия: 0x800 - 12, 0x1000 - 4, 0x80 - 2.
/// </remarks>
/// <param name="ConditionFlags">Режим проверки: 0x40000000 - «или», 0x20000000 - «и»; без этих битов условие не проверяется.</param>
/// <param name="ConditionMask">Маска проверяемых признаков состояния.</param>
/// <param name="ConditionInvertMask">Признаки, для которых ожидается значение «сброшен».</param>
public readonly record struct ControlCommandConditionRaw(
    uint ConditionFlags,
    uint ConditionMask,
    uint ConditionInvertMask);
