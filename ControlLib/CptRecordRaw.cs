using Common;

namespace ControlLib;

/// <summary>
/// Запись контрольной точки CPT (36 байт): деталь-владелец, связанная деталь, положение и направление в системе детали-владельца.
/// Положение дула в объекте = положение точки × матрица детали-владельца в позе. Длина направления масштабирует порождаемый в точке эффект
/// (команда 4 CTL, см. README, §7.4).
/// </summary>
/// <param name="Offset">Смещение записи от начала файла (для отладки).</param>
/// <param name="Unknown0">+0x00: назначение не выяснено. В данных два значения: 0 - 882 точки, 0x80000000 - 385.</param>
/// <param name="OwnerPieceIndex">+0x04: деталь-владелец точки (локальный индекс детали меша). В данных 0..29, значения −1 нет.</param>
/// <param name="TargetPieceIndex">+0x08: связанная визуальная/функциональная деталь; у колёс шасси точка принадлежит корню, а цель - колесо.
/// Различие Owner/Target не окончательно (гипотеза). В данных −1 у 162 точек (без цели), совпадает с владельцем у 1018, диапазон −1..45.</param>
/// <param name="Position">+0x0C: положение точки в системе детали-владельца.</param>
/// <param name="Direction">+0x18: направление (не нормализовано). Длина 0.02..4.85, нулевых нет.</param>
public sealed record CptRecordRaw(
    long Offset,
    int Unknown0,
    int OwnerPieceIndex,
    int TargetPieceIndex,
    Vector3 Position,
    Vector3 Direction);
