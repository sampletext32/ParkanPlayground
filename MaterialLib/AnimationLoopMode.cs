namespace MaterialLib;

/// <summary>
/// Режим повтора анимации материала (биты 0..2 слова анимации); применяется в <c>MatManager::AnimateFrame</c>
/// к времени <c>(g_game_time − lastUsedTime)</c> по длительности последнего ключа.
/// </summary>
/// <remarks>Статистика по 685 анимациям: цикл - 607, пинг-понг - 58, один раз - 19, случайно - 1 (<c>DEFL_G</c>).</remarks>
public enum AnimationLoopMode : int
{
    /// <summary>Цикл: позиция = время по модулю длительности.</summary>
    Loop = 0,

    /// <summary>Пинг-понг: чётные проходы вперёд, нечётные назад (треугольная волна). Материалы AIGRETTE_*, B_MN_01*, B_S13, JET1/2/4 и др. (54 с двумя и более ключами).</summary>
    PingPong = 1,

    /// <summary>
    /// Один раз. После конца длительности движок берёт последний ключ с позицией 0 и следующим ключом 0, поэтому доля интерполяции
    /// отрицательна и цвета по маске экстраполируются от последней стадии (EXPL1..4, CLOUD*, SPLASH1..3 - 19 материалов).
    /// </summary>
    Clamp = 2,

    /// <summary>Случайная позиция внутри длительности при каждом обращении (<c>rand() % длительность</c>). Единственный материал - <c>DEFL_G</c> (4 стадии по 5 мс).</summary>
    Random = 3
}
